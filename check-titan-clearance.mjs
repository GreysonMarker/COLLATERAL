import assert from 'node:assert/strict';
import * as T from './dist/vendor/three.module.js';
import {CollisionWorld} from './dist/collision.js';
import {createDestruction} from './dist/destruction.js';
const scene=new T.Scene(),m=new T.MeshStandardMaterial(),g=new T.BoxGeometry(32,360,32).toNonIndexed();g.translate(0,180,0);
const b={x:0,z:0,ranges:[{m,b:{geometry:g},start:0,end:g.attributes.position.count}],solids:[]};
const solid={x1:-16,x2:16,y1:0,y2:360,z1:-16,z2:16,building:b};b.solids.push(solid);
const world=new CollisionWorld([solid],()=>0),d=createDestruction(scene,world,{concrete:m,roofmat:m,mobile:true});
const p=new T.Vector3(0,30,-16),direction=new T.Vector3(0,0,1);
assert(world.sphereHit(p,8,false));
d.punch(b,p,direction,'serious',{origin:p.clone(),width:12,reach:12,spread:0,sphere:true});
assert(!b.active,'exercise deferred destruction');
assert(!world.sphereHit(p,8,false),'spherical titan cut must clear collision before preparation');
assert(world.sphereHit(new T.Vector3(0,100,-16),8,false),'uncut building remains solid');
const obstacle={x1:0,x2:2,y1:0,y2:100,z1:-10,z2:10};
const recoveryWorld=new CollisionWorld([obstacle],()=>0);recoveryWorld.bodyRadius=.28;
const position=new T.Vector3(-.1,0,0),offsets=[new T.Vector3(0,1,0)];
assert(!recoveryWorld.recover(position,offsets,{verticalOnly:true}));assert.equal(position.x,-.1,'titan recovery never shoves backward');
const ordinary=position.clone();assert(recoveryWorld.recover(ordinary,offsets));assert(ordinary.x<position.x,'normal hero recovery remains available');
obstacle.fallingSection=true;recoveryWorld.titanWalking=true;assert(!recoveryWorld.bodyHit(position,offsets));recoveryWorld.titanWalking=false;assert(recoveryWorld.bodyHit(position,offsets));
console.log('Deferred titan openings, unchanged intact walls, no sideways recovery and actor-scoped falling-rubble clearance pass.');
